export const AI_LABEL = 'AI-assisted — generated by software and may contain errors. Not reviewed by a clinician unless stated.';

/** Redact direct identifiers before any text leaves the platform. */
export function redact(text: string, names: string[] = []): string {
  let out = text
    .replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g, '[email]')
    .replace(/\+?\d[\d\s-]{8,}\d/g, '[phone]')
    .replace(/\b[A-Z]{2,5}[-/]?\d{4,}\b/g, '[id]');
  for (const n of names.filter((x) => x && x.length > 1)) {
    out = out.replace(new RegExp(`\\b${n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi'), '[name]');
  }
  return out;
}

async function assertAiAllowed(p: Principal): Promise<Types.ObjectId> {
  assertPermission(p, 'ai.use');
  const hospitalId = requireTenant(p);
  const hospital = await HospitalModel.findById(hospitalId).select('settings.aiFeaturesEnabled');
  if (hospital?.settings?.aiFeaturesEnabled === false) throw new AppError('FEATURE_NOT_ENTITLED', 'AI features are disabled for this hospital');
  await assertFeature(hospitalId, 'AI_ASSIST');
  return hospitalId;
}

type Feature = 'EXPLAIN_INSTRUCTION' | 'CLASSIFY_MESSAGE' | 'SUMMARISE_RECOVERY' | 'TRANSCRIBE';

async function logInteraction(args: {
  hospitalId: Types.ObjectId;
  feature: Feature;
  promptVersion: string;
  p: Principal;
  patientId?: Types.ObjectId;
  episodeId?: Types.ObjectId;
  sourceRef?: { kind: string; id: Types.ObjectId; index?: number };
  input: string;
  status: 'SUCCEEDED' | 'INVALID_OUTPUT' | 'FAILED' | 'FALLBACK' | 'REJECTED_SAFETY';
  output?: unknown;
  latencyMs?: number;
  errorCode?: string;
}) {
  const doc = await AiInteractionModel.create({
    hospitalId: args.hospitalId,
    feature: args.feature,
    provider: provider.name,
    model: provider.model,
    promptVersion: args.promptVersion,
    requestedBy: args.p.userId,
    patientId: args.patientId,
    episodeId: args.episodeId,
    sourceRef: args.sourceRef,
    inputHash: sha256(args.input),
    status: args.status,
    output: args.output,
    latencyMs: args.latencyMs,
    errorCode: args.errorCode,
  });
  await recordUsage(args.hospitalId, 'AI_REQUESTS', 1);
  await audit({ action: `AI_${args.feature}`, resourceType: 'AiInteraction', resourceId: String(doc._id), patientId: args.patientId ? String(args.patientId) : undefined, metadata: { status: args.status, model: provider.model, promptVersion: args.promptVersion } });
  return doc;
}

/**
 * Run a model call and validate. Returns `null` output on any failure (callers then use
 * their non-AI fallback) — AI failure never blocks a clinical workflow.
 */
async function callModel<T>(
  req: Parameters<AiProvider['generate']>[0],
  parse: (text: string) => T | null,
): Promise<{ output: T | null; status: 'SUCCEEDED' | 'INVALID_OUTPUT' | 'FAILED'; latencyMs?: number; errorCode?: string }> {
  if (!provider.isAvailable()) return { output: null, status: 'FAILED', errorCode: 'UNAVAILABLE' };
  try {
    const res = await provider.generate(req);
    const parsed = parse(res.text);
    return parsed ? { output: parsed, status: 'SUCCEEDED', latencyMs: res.latencyMs } : { output: null, status: 'INVALID_OUTPUT', latencyMs: res.latencyMs, errorCode: 'SCHEMA' };
  } catch (err) {
    const kind = err instanceof AiProviderError ? err.kind : 'PROVIDER_ERROR';
    logger.warn({ kind, feature: req.json }, 'AI call failed');
    return { output: null, status: 'FAILED', errorCode: kind };
  }
}

/* ------------------------ Feature 1: plain-language explanations ------------------------ */

const SECTIONS = ['clinicalInstructions', 'medications', 'woundCare', 'activityRestrictions', 'dietaryInstructions', 'warningSigns', 'education'] as const;

export async function explainInstruction(p: Principal, input: { dischargePlanVersionId: string; section: (typeof SECTIONS)[number]; itemIndex: number; language: 'en' | 'ha' | 'pcm' }) {
  const hospitalId = await assertAiAllowed(p);
  const version = await DischargePlanVersionModel.findOne({ _id: input.dischargePlanVersionId, hospitalId });
  if (!version) throw errors.notFound('Discharge plan');
  await loadEpisode(p, version.episodeId as Types.ObjectId, 'recovery.read');
  if (version.status !== 'APPROVED' && version.status !== 'SUPERSEDED') throw errors.validation('Only approved instructions can be explained');
  if (p.kind !== 'STAFF' && version.status !== 'APPROVED') throw errors.notFound('Discharge plan');

  const content = dischargeContentSchema.parse(version.content);
  let source: { title: string; details: string } | undefined;
  if (input.section === 'medications') {
    const m = content.medications[input.itemIndex];
    if (m) source = { title: `${m.name}${m.strength ? ` ${m.strength}` : ''}`, details: [`Dose: ${m.dose}`, `How often: ${m.frequencyText}`, m.instructions].filter(Boolean).join('. ') };
  } else {
    source = content[input.section][input.itemIndex];
  }
  if (!source) throw errors.notFound('Instruction');

  // Cached explanation for this exact instruction + language.
  const cached = await AiInteractionModel.findOne({
    hospitalId,
    feature: 'EXPLAIN_INSTRUCTION',
    'sourceRef.id': version._id,
    'sourceRef.kind': `${input.section}:${input.language}`,
    'sourceRef.index': input.itemIndex,
    status: 'SUCCEEDED',
    promptVersion: PROMPT_VERSIONS.EXPLAIN_INSTRUCTION,
  });
  const original = { title: source.title, details: source.details };
  if (cached) return { original, explanation: cached.output, aiAssisted: true, label: AI_LABEL, interactionId: String(cached._id) };

  const prompt = explainInstructionPrompt(source, input.language);
  const result = await callModel({ ...prompt, json: true, temperature: 0.2 }, (t) => parseModelJson(explanationOutput, t));
  let status: 'SUCCEEDED' | 'INVALID_OUTPUT' | 'FAILED' | 'REJECTED_SAFETY' = result.status;
  let output = result.output;
  if (output) {
    const check = explanationIsFaithful(`${source.title} ${source.details}`, output);
    if (!check.ok) {
      status = 'REJECTED_SAFETY';
      output = null;
      logger.warn({ reason: check.reason }, 'AI explanation rejected by meaning-preservation guard');
    }
  }
  const log = await logInteraction({
    hospitalId,
    feature: 'EXPLAIN_INSTRUCTION',
    promptVersion: PROMPT_VERSIONS.EXPLAIN_INSTRUCTION,
    p,
    patientId: version.patientId as Types.ObjectId,
    episodeId: version.episodeId as Types.ObjectId,
    sourceRef: { kind: `${input.section}:${input.language}`, id: version._id, index: input.itemIndex },
    input: JSON.stringify(source),
    status: output ? 'SUCCEEDED' : status === 'REJECTED_SAFETY' ? 'REJECTED_SAFETY' : 'FALLBACK',
    output: output ?? undefined,
    latencyMs: result.latencyMs,
    errorCode: result.errorCode,
  });
  // Fallback: the original approved instruction (always safe).
  return output
    ? { original, explanation: output, aiAssisted: true, label: AI_LABEL, interactionId: String(log._id) }
    : { original, explanation: null, aiAssisted: false, fallbackReason: 'A simplified explanation is not available right now. The original instruction from your care team is shown.', interactionId: String(log._id) };
}

/* ------------------------ Feature 2: message understanding ------------------------ */

/** Keyword fallback when AI is unavailable. Deliberately conservative. */
export function fallbackClassify(text: string): ClassificationOutput {
  const t = text.toLowerCase();
  const category: ClassificationOutput['category'] = /wound|stitch|dressing|incision|fluid|pus/.test(t)
    ? 'WOUND'
    : /tablet|medic|drug|dose|pill|pharm/.test(t)
      ? 'MEDICATION'
      : /appointment|clinic|reschedul|visit/.test(t)
        ? 'APPOINTMENT'
        : /exercise|physio|walk/.test(t)
          ? 'REHABILITATION'
          : /pain|fever|bleed|vomit|breath|dizz|swell/.test(t)
            ? 'SYMPTOM'
            : 'GENERAL';
  const routing: Record<ClassificationOutput['category'], ClassificationOutput['suggestedRouting']> = {
    WOUND: 'NURSING_REVIEW',
    MEDICATION: 'MEDICATION_TEAM',
    APPOINTMENT: 'ADMINISTRATIVE',
    REHABILITATION: 'NURSING_REVIEW',
    SYMPTOM: 'CLINICIAN_REVIEW',
    ADMINISTRATIVE: 'ADMINISTRATIVE',
    GENERAL: 'GENERAL_ENQUIRY',
  };
  return { category, reportedSymptoms: [], reportedDuration: null, expressedSeverity: 'UNCLEAR', missingInformation: [], suggestedRouting: routing[category] };
}

export async function classifyMessage(p: Principal, messageId: string) {
  if (p.kind !== 'STAFF') throw errors.forbidden();
  const hospitalId = await assertAiAllowed(p);
  assertPermission(p, 'messages.read');
  const message = await MessageModel.findOne({ _id: messageId, hospitalId });
  if (!message) throw errors.notFound('Message');
  const conv = await ConversationModel.findOne({ _id: message.conversationId, hospitalId });
  if (!conv?.patientId || !conv.episodeId) throw errors.validation('Only patient messages linked to an episode can be classified');
  await loadEpisode(p, conv.episodeId as Types.ObjectId, 'messages.read');
  const patient = await PatientModel.findOne({ _id: conv.patientId, hospitalId });
  if (patient && !(await hasConsent(hospitalId, patient._id, 'AI_ASSISTED_FEATURES'))) {
    const output = fallbackClassify(message.body);
    return { original: message.body, classification: output, aiAssisted: false, fallbackReason: 'Patient has not consented to AI-assisted processing; keyword routing used.' };
  }

  const text = redact(message.body, [patient?.firstName ?? '', patient?.lastName ?? '']);
  const prompt = classifyMessagePrompt(text);
  const result = await callModel({ ...prompt, json: true }, (t) => parseModelJson(classificationOutput, t));
  const output = result.output ?? fallbackClassify(message.body);
  const log = await logInteraction({
    hospitalId,
    feature: 'CLASSIFY_MESSAGE',
    promptVersion: PROMPT_VERSIONS.CLASSIFY_MESSAGE,
    p,
    patientId: conv.patientId as Types.ObjectId,
    episodeId: conv.episodeId as Types.ObjectId,
    sourceRef: { kind: 'Message', id: message._id },
    input: text,
    status: result.output ? 'SUCCEEDED' : 'FALLBACK',
    output,
    latencyMs: result.latencyMs,
    errorCode: result.errorCode,
  });
  message.aiClassificationId = log._id;
  await message.save();
  // The classification is a routing SUGGESTION. Escalation decisions remain with staff and
  // hospital-approved rules; nothing is escalated automatically from AI output.
  return { original: message.body, classification: output, aiAssisted: !!result.output, label: result.output ? AI_LABEL : undefined, interactionId: String(log._id) };
}

/* ------------------------ Feature 3: clinical team summaries ------------------------ */

/** Build de-identified, structured facts for an episode/period — the summary's only source. */
export async function buildRecoveryFacts(hospitalId: Types.ObjectId, episodeId: Types.ObjectId, periodDays: number, includeMedication: boolean) {
  const since = DateTime.now().minus({ days: periodDays }).toJSDate();
  const [checkIns, symptoms, missed, medEvents, appts, alerts] = await Promise.all([
    CheckInModel.find({ hospitalId, episodeId, createdAt: { $gte: since } }).populate({ path: 'templateId', select: 'name questions', options: { skipTenantGuard: true } }).sort({ createdAt: 1 }),
    SymptomReportModel.find({ hospitalId, episodeId, createdAt: { $gte: since } }).sort({ createdAt: 1 }),
    RecoveryTaskModel.aggregate([{ $match: { hospitalId, episodeId, status: 'MISSED', dueAt: { $gte: since } } }, { $group: { _id: '$type', count: { $sum: 1 } } }]),
    includeMedication ? MedicationEventModel.find({ hospitalId, episodeId, createdAt: { $gte: since }, status: { $in: ['REPORTED_MISSED', 'UNABLE_TO_OBTAIN', 'REQUIRES_REVIEW', 'NOT_RESPONDED'] } }).populate({ path: 'medicationOrderId', select: 'name', options: { skipTenantGuard: true } }) : Promise.resolve([]),
    AppointmentModel.find({ hospitalId, episodeId, status: { $in: ['SCHEDULED', 'CONFIRMED', 'RESCHEDULE_REQUESTED'] } }).sort({ scheduledAt: 1 }).limit(5),
    AlertModel.find({ hospitalId, episodeId, status: { $nin: ['RESOLVED', 'CLOSED'] } }).select('title priority status createdAt'),
  ]);
  return {
    reportingPeriod: { from: DateTime.fromJSDate(since).toISODate(), to: DateTime.now().toISODate(), days: periodDays },
    checkInCount: checkIns.length,
    checkIns: checkIns.map((c) => ({
      date: DateTime.fromJSDate(c.get('createdAt') as Date).toISODate(),
      form: (c.templateId as unknown as { name?: string })?.name,
      answers: c.answers,
    })),
    symptomReports: symptoms.map((s) => ({ date: DateTime.fromJSDate(s.get('createdAt') as Date).toISODate(), severity: s.severity, trend: s.trend, code: s.symptomCode, description: redact(s.description) })),
    missedActivities: missed.map((m: { _id: string; count: number }) => ({ type: m._id, count: m.count })),
    medicationConcerns: (medEvents as Array<{ status: string; accessProblem?: string | null; medicationOrderId?: unknown }>).map((e) => ({ status: e.status, accessProblem: e.accessProblem ?? undefined, medication: (e.medicationOrderId as { name?: string } | undefined)?.name })),
    outstandingAppointments: appts.map((a) => ({ type: a.type, date: DateTime.fromJSDate(a.scheduledAt).toISODate(), status: a.status })),
    openAlerts: alerts.map((a) => ({ title: a.title, priority: a.priority, status: a.status })),
  };
}

function fallbackSummary(facts: Awaited<ReturnType<typeof buildRecoveryFacts>>) {
  return {
    overview: `${facts.checkInCount} check-in(s) and ${facts.symptomReports.length} symptom report(s) in the last ${facts.reportingPeriod.days} days. ${facts.openAlerts.length} open alert(s).`,
    reportedSymptoms: facts.symptomReports.map((s) => `${s.date}: ${s.severity.toLowerCase()} (${s.trend.toLowerCase()}) — "${s.description}"`),
    missedActivities: facts.missedActivities.map((m) => `${m.count} missed ${m.type.toLowerCase().replace(/_/g, ' ')} task(s)`),
    medicationConcerns: facts.medicationConcerns.map((m) => `${m.medication ?? 'Medication'}: ${m.status.toLowerCase().replace(/_/g, ' ')}${m.accessProblem ? ` (${m.accessProblem.toLowerCase()})` : ''}`),
    outstandingAppointments: facts.outstandingAppointments.map((a) => `${a.type.toLowerCase().replace(/_/g, ' ')} on ${a.date} (${a.status.toLowerCase()})`),
    openAlerts: facts.openAlerts.map((a) => `${a.priority}: ${a.title} (${a.status.toLowerCase()})`),
    itemsRequiringReview: [
      ...facts.symptomReports.filter((s) => s.severity === 'SEVERE' || s.trend === 'WORSENING').map((s) => `Symptom report ${s.date} (${s.severity.toLowerCase()}, ${s.trend.toLowerCase()})`),
      ...facts.medicationConcerns.filter((m) => m.status === 'UNABLE_TO_OBTAIN').map((m) => `Medication access: ${m.medication ?? 'medication'}`),
    ],
  };
}

export async function summariseRecovery(p: Principal, input: { episodeId: string; periodDays: number }) {
  if (p.kind !== 'STAFF') throw errors.forbidden('Clinical summaries are for authorised staff');
  const hospitalId = await assertAiAllowed(p);
  const episode = await loadEpisode(p, input.episodeId, 'checkins.read');
  const facts = await buildRecoveryFacts(hospitalId, episode._id, input.periodDays, p.permissions.has('medication.read'));
  const deterministic = fallbackSummary(facts);
  const consent = await hasConsent(hospitalId, episode.patientId as Types.ObjectId, 'AI_ASSISTED_FEATURES');
  if (!consent) return { facts, summary: deterministic, aiAssisted: false, fallbackReason: 'Patient has not consented to AI-assisted processing; structured summary shown.' };

  const factsJson = JSON.stringify(facts);
  const prompt = summariseRecoveryPrompt(factsJson);
  const result = await callModel({ ...prompt, json: true, maxOutputTokens: 1500 }, (t) => parseModelJson(summaryOutput, t));
  let output = result.output;
  let status: 'SUCCEEDED' | 'FALLBACK' | 'REJECTED_SAFETY' = output ? 'SUCCEEDED' : 'FALLBACK';
  if (output && !summaryIsGrounded(factsJson, output).ok) {
    output = null;
    status = 'REJECTED_SAFETY';
  }
  const log = await logInteraction({
    hospitalId,
    feature: 'SUMMARISE_RECOVERY',
    promptVersion: PROMPT_VERSIONS.SUMMARISE_RECOVERY,
    p,
    patientId: episode.patientId as Types.ObjectId,
    episodeId: episode._id,
    input: factsJson,
    status,
    output: output ?? deterministic,
    latencyMs: result.latencyMs,
    errorCode: result.errorCode,
  });
  return {
    facts,
    summary: output ?? deterministic,
    aiAssisted: !!output,
    label: output ? `${AI_LABEL} Check against the source data before acting.` : undefined,
    interactionId: String(log._id),
  };
}

/* ------------------------ Feature 4: recovery pattern insights ------------------------ */

/**
 * Operational observations (NOT diagnoses), computed deterministically from data so they
 * are reproducible and explainable.
 */
export async function patternInsights(p: Principal, episodeId: string) {
  if (p.kind !== 'STAFF') throw errors.forbidden();
  const episode = await loadEpisode(p, episodeId, 'checkins.read');
  const hospitalId = requireTenant(p);
  const since = DateTime.now().minus({ days: 14 }).toJSDate();
  const insights: Array<{ code: string; message: string; evidence: Record<string, unknown> }> = [];

  const missedCheckins = await RecoveryTaskModel.countDocuments({ hospitalId, episodeId: episode._id, type: 'CHECK_IN', status: 'MISSED', dueAt: { $gte: since } });
  if (missedCheckins >= 2) insights.push({ code: 'REPEATED_MISSED_CHECKINS', message: `${missedCheckins} check-ins missed in the last 14 days.`, evidence: { missedCheckins } });

  if (p.permissions.has('medication.read')) {
    const access = await MedicationEventModel.countDocuments({ hospitalId, episodeId: episode._id, status: 'UNABLE_TO_OBTAIN', createdAt: { $gte: since } });
    if (access >= 2) insights.push({ code: 'REPEATED_MEDICATION_ACCESS_PROBLEMS', message: `${access} reports of being unable to obtain medication in 14 days.`, evidence: { access } });
  }

  const alertIds = await AlertModel.distinct('_id', { hospitalId, episodeId: episode._id });
  const noAnswer = await AlertActionModel.countDocuments({ hospitalId, alertId: { $in: alertIds }, type: 'PATIENT_CONTACT_ATTEMPT', contactOutcome: { $in: ['NO_ANSWER', 'VOICEMAIL'] }, createdAt: { $gte: since } });
  if (noAnswer >= 2) insights.push({ code: 'UNANSWERED_CONTACT_ATTEMPTS', message: `${noAnswer} unanswered contact attempts in 14 days.`, evidence: { noAnswer } });

  const missedRehab = await RehabilitationSessionModel.countDocuments({ hospitalId, episodeId: episode._id, status: 'MISSED', scheduledAt: { $gte: since } });
  if (missedRehab >= 2) insights.push({ code: 'REPEATED_MISSED_REHABILITATION', message: `${missedRehab} rehabilitation sessions missed in 14 days.`, evidence: { missedRehab } });

  // Rising patient-reported pain: numeric answers whose key mentions "pain".
  const checkIns = await CheckInModel.find({ hospitalId, episodeId: episode._id, createdAt: { $gte: since } }).sort({ createdAt: 1 }).select('answers createdAt');
  const pain = checkIns
    .map((c) => {
      const entry = Object.entries((c.answers ?? {}) as Record<string, unknown>).find(([k, v]) => /pain/.test(k) && typeof v === 'number');
      return entry ? (entry[1] as number) : undefined;
    })
    .filter((v): v is number => v !== undefined);
  if (pain.length >= 3) {
    const last3 = pain.slice(-3);
    if (last3[0]! < last3[1]! && last3[1]! < last3[2]!) {
      insights.push({ code: 'INCREASING_REPORTED_PAIN', message: `Patient-reported pain score increased across the last 3 check-ins (${last3.join(' → ')}).`, evidence: { scores: last3 } });
    }
  }
  return { insights, disclaimer: 'Operational observations from recorded activity — not clinical assessments or diagnoses.' };
}

/* ------------------------ Feature 5: voice messages ------------------------ */

export async function transcribeVoice(p: Principal, documentId: string) {
  const hospitalId = await assertAiAllowed(p);
  const doc = await DocumentModel.findOne({ _id: documentId, hospitalId, status: 'ACTIVE' }).select('+storageKey');
  if (!doc || doc.mimeType !== 'audio/mp4') throw errors.notFound('Voice message');
  if (!doc.patientId) throw errors.notFound('Voice message');
  if (p.kind === 'STAFF') await loadEpisode(p, doc.episodeId as Types.ObjectId, 'messages.read');
  else if (!(p.patientIds.includes(String(doc.patientId)) || p.caregiverGrants.some((g) => g.patientId === String(doc.patientId)))) throw errors.notFound('Voice message');
  if (!(await hasConsent(hospitalId, doc.patientId as Types.ObjectId, 'AI_ASSISTED_FEATURES'))) {
    throw new AppError('CONSENT_REQUIRED', 'AI-assisted transcription requires the patient\'s consent');
  }
  const audio = await storage().read(doc.storageKey);
  const prompt = transcribePrompt();
  const result = await callModel({ ...prompt, json: true, inlineData: { mimeType: doc.mimeType, base64: audio.toString('base64') }, maxOutputTokens: 4000 }, (t) => parseModelJson(transcriptionOutput, t));
  const log = await logInteraction({
    hospitalId,
    feature: 'TRANSCRIBE',
    promptVersion: PROMPT_VERSIONS.TRANSCRIBE,
    p,
    patientId: doc.patientId as Types.ObjectId,
    episodeId: doc.episodeId as Types.ObjectId | undefined,
    sourceRef: { kind: 'Document', id: doc._id },
    input: doc.sha256,
    status: result.output ? 'SUCCEEDED' : 'FALLBACK',
    output: result.output ?? undefined,
    latencyMs: result.latencyMs,
    errorCode: result.errorCode,
  });
  // Retain original audio only with explicit consent.
  if (!(await hasConsent(hospitalId, doc.patientId as Types.ObjectId, 'VOICE_RECORDING_RETENTION'))) {
    doc.status = 'DELETED';
    doc.deletedAt = new Date();
    await doc.save();
  }
  if (!result.output) throw new AppError('AI_UNAVAILABLE', 'Transcription is not available right now. Please type your message instead.');
  return { transcription: result.output, interactionId: String(log._id), label: 'Automatic transcription — may contain errors. Please check and correct it.' };
}

/** Patient or clinician corrects AI output (e.g. transcription). Original output is preserved. */
export async function reviewInteraction(p: Principal, interactionId: string, input: { correctedOutput?: unknown; accepted: boolean }) {
  const hospitalId = requireTenant(p);
  const interaction = await AiInteractionModel.findOne({ _id: interactionId, hospitalId });
  if (!interaction) throw errors.notFound('AI result');
  if (p.kind === 'STAFF') {
    if (interaction.episodeId) await loadEpisode(p, interaction.episodeId as Types.ObjectId, 'recovery.read');
  } else if (String(interaction.requestedBy) !== p.userId) {
    throw errors.notFound('AI result');
  }
  interaction.review = { reviewedBy: new Types.ObjectId(p.userId), reviewedAt: new Date(), correctedOutput: input.correctedOutput, accepted: input.accepted };
  await interaction.save();
  await audit({ action: 'AI_OUTPUT_REVIEWED', resourceType: 'AiInteraction', resourceId: interactionId, metadata: { accepted: input.accepted, corrected: input.correctedOutput !== undefined } });
  return interaction;
}
